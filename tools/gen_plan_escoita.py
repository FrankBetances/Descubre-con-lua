def build_cmudict(palabras: set[str]) -> None:
    lic = CMU_LIC.read_text(encoding="utf-8").splitlines()
    entries: list[str] = []
    found: set[str] = set()
    for line in CMU_DICT.read_text(encoding="utf-8", errors="ignore").splitlines():
        if line.startswith(";;;") or not line.strip():
            continue
        parts = line.split("#")[0].strip().split()
        if not parts:
            continue
        base = re.sub(r"\(\d+\)$", "", parts[0].lower())
        if base in palabras:
            found.add(base)
            phones = " ".join(parts[1:])
            entries.append(f"{parts[0].lower()} {phones}")
    faltan = sorted(palabras - found)
    if faltan:
        raise SystemExit(f"Faltan en CMUdict: {faltan}")
    out = [
        "# CMU Pronouncing Dictionary (cmudict) — subconjunto usado en Escoita",
        "# Fuente: https://github.com/cmusphinx/cmudict (licencia BSD)",
        "#",
    ] + [("# " + l).rstrip() for l in lic] + [""] + sorted(entries) + [""]
    OUT_CMU.write_text("\n".join(out), encoding="utf-8")


def main() -> None:
    steam_refs = load_steam_refs()
    specs = build_specs()
    assert len(specs) == 40, f"Esperadas 40 piezas, hay {len(specs)}"

    piezas = []
    missing_laminas = set()
    for sp in specs:
        curso, mes, a, b, fonema, nota, acierto, fallo, pista, tema, fases, mad, mnota = sp
        pieza = make_piece(
            curso,
            mes,
            steam_refs[(curso, mes)],
            a=a,
            b=b,
            fonema=fonema,
            nota=nota,
            acierto=acierto,
            fallo=fallo,
            pista=pista,
            tema=tema,
            fases=fases,
            modelo_adulto=mad,
            modelo_nota=mnota,
        )
        piezas.append(pieza)
        for obj in [pieza["par"]["a"], pieza["par"]["b"], *pieza["progresion"]["fases"]]:
            if obj["lamina"] not in EXISTING_LAMINAS:
                missing_laminas.add(obj["lamina"])

    OUT_PLAN.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "version": 1,
        "_doc": "Plan mensual de xogos de escoita e expansión semántica orientados ao STEAM (40 pezas: 2-3, 3-4, 4-5 e 5-6; meses 1-10). O-20261119-8, O-20261118-3 e R-STEAM.",
        "piezas": piezas,
    }
    OUT_PLAN.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    palabras = set()
    for pza in piezas:
        palabras.add(pza["par"]["a"]["en"].lower())
        palabras.add(pza["par"]["b"]["en"].lower())
    build_cmudict(palabras)
