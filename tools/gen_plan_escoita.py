EXISTING_LAMINAS = {p.stem for p in LAMINAS_DIR.glob("*.json")}


def lam_key(en_word: str) -> str:
    slug = en_word.lower().replace(" ", "_")
    for cand in (f"pal_{slug}", slug, f"pal_pal_{slug}"):
        if cand in EXISTING_LAMINAS:
            return cand
    return f"pal_{slug}"


def load_steam_refs() -> dict[tuple[str, int], dict]:
    lec = json.loads(LECCIONS_PATH.read_text(encoding="utf-8"))
    out: dict[tuple[str, int], dict] = {}
    for curso, cdata in lec["cursos"].items():
        for idx, unidad in enumerate(cdata["unidades"], 1):
            out[(curso, idx)] = unidad["steam"]
    return out


def make_piece(
    curso: str,
    mes: int,
    steam_ref: dict,
    *,
    a: tuple[str, str, str, str, str],
    b: tuple[str, str, str, str, str],
    fonema: str,
    nota: tuple[str, str],
    acierto: tuple[str, str],
    fallo: tuple[str, str],
    pista: tuple[str, str],
    tema: tuple[str, str],
    fases: list[tuple[str, str, str, str, str, str, str, str, str]],
    modelo_adulto: list[str],
    modelo_nota: tuple[str, str],
) -> dict:
    # a/b = (en, gl, es, steam_gl, steam_es)
    # fase = (tipo, en, gl, es, frase_en, acc_gl, acc_es, steam_gl, steam_es)
    return {
        "curso": curso,
        "mes": mes,
        "steam": {
            "id": steam_ref["id"],
            "titulo": {
                "gl": steam_ref["titulo"]["gl"],
                "es": steam_ref["titulo"]["es"],
            },
        },
        "fuente": "nueva",
        "par": {
            "a": {
                "en": a[0],
                "gl": a[1],
                "es": a[2],
                "lamina": lam_key(a[0]),
                "steam": {"gl": a[3], "es": a[4]},
            },
            "b": {
                "en": b[0],
                "gl": b[1],
                "es": b[2],
                "lamina": lam_key(b[0]),
                "steam": {"gl": b[3], "es": b[4]},
            },
            "fonema": fonema,
            "nota": {"gl": nota[0], "es": nota[1]},
            "mision_acerto": {"gl": acierto[0], "es": acierto[1]},
            "mision_fallo": {"gl": fallo[0], "es": fallo[1]},
            "pista": {"gl": pista[0], "es": pista[1]},
        },
        "progresion": {
            "tema": {"gl": tema[0], "es": tema[1]},
            "fases": [
                {
                    "tipo": tipo,
                    "en": en,
                    "gl": gl,
                    "es": es,
                    "lamina": lam_key(en),
                    "frase": frase,
                    "accion": {"gl": acc_gl, "es": acc_es},
                    "steam": {"gl": st_gl, "es": st_es},
                }
                for (tipo, en, gl, es, frase, acc_gl, acc_es, st_gl, st_es) in fases
            ],
        },
        "modelo": {
            "neno": fases[0][1],
            "adulto": modelo_adulto,
            "nota": {"gl": modelo_nota[0], "es": modelo_nota[1]},
        },
    }


