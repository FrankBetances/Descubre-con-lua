def build_cmudict(palabras: set[str]) -> None:
    lic = CMU_LIC.read_text(encoding="utf-8").splitlines()
    entries: list[str] = []
    found: set[str] = set()
    for line in CMU_DICT.read_text(encoding="utf-8", errors="ignore").splitlines():
        if line.startswith(";;;") or not line.strip():
            continue
        parts = line.split("#")[0].strip().split()
        if not parts:
            continue
        base = re.sub(r"\(\d+\)$", "", parts[0].lower())
        if base in palabras:
            found.add(base)
            phones = " ".join(parts[1:])
            entries.append(f"{parts[0].lower()} {phones}")
    faltan = sorted(palabras - found)
    if faltan:
        raise SystemExit(f"Faltan en CMUdict: {faltan}")
    out = [
        "# CMU Pronouncing Dictionary (cmudict) — subconjunto usado en Escoita",
        "# Fuente: https://github.com/cmusphinx/cmudict (licencia BSD)",
        "#",
    ] + [("# " + l).rstrip() for l in lic] + [""] + sorted(entries) + [""]
    OUT_CMU.write_text("\n".join(out), encoding="utf-8")


