    for p in piezas:
        k = (p["curso"], p["mes"])
        if k not in PENSAMIENTO:
            raise KeyError(f"Falta pensamiento para {k}")
        p["pensamiento"] = PENSAMIENTO[k]
    PLAN.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"OK: añadido bloque pensamiento (4 momentos) a las {len(piezas)} piezas en {PLAN.relative_to(RAIZ)}")
    return 0


